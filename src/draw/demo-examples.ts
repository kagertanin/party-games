import type { Stroke } from "./canvas";

type Point = Stroke["points"][number];
const ink = "#352652";
const coral = "#e45b58";
const green = "#32816b";
const blue = "#4284ae";
const gold = "#db972b";

function line(color: string, width: number, ...points: Point[]): Stroke {
  return { color, width, points, erase: false };
}

function oval(color: string, width: number, x: number, y: number, rx: number, ry: number): Stroke {
  const points: Point[] = [];
  for (let i = 0; i <= 36; i++) {
    const a = (i * 2 * Math.PI) / 36;
    points.push([Math.round(x + rx * Math.cos(a)), Math.round(y + ry * Math.sin(a))]);
  }
  return line(color, width, ...points);
}

